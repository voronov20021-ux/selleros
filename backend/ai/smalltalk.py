"""
smalltalk.py — живые ответы на бытовые реплики.

«Привет», «спасибо», «ок» не должны уходить в модель:
это лишняя секунда ожидания, лишние деньги и риск получить
в ответ статью про маркетплейсы.

Отвечаем локально, мгновенно и по-разному, чтобы не выглядело шаблоном.
Ответ учитывает контекст: если товар уже разобран, Seller AI
предложит вернуться именно к нему.
"""

import random

from backend.ai.intents import _normalize
from backend.config import AI_NAME

# --------------------------------------------------------------------------- #
# Наборы реплик
# --------------------------------------------------------------------------- #

GREETINGS = (
    "Привет! Рад тебя видеть 👋",
    "Привет! На связи.",
    "Здорово! Я тут.",
    "Привет 👋",
)

MORNING = (
    "Доброе утро! Готов работать.",
    "Утро доброе 👋",
)

EVENING = (
    "Добрый вечер!",
    "Вечер добрый. На связи.",
)

THANKS = (
    "Обращайся.",
    "Не за что. Что дальше?",
    "Всегда пожалуйста 🙂",
    "Рад, если помогло.",
)

ACK = (
    "Принял.",
    "Понял тебя.",
    "Ок.",
    "Хорошо.",
)

BYE = (
    "До связи! Заходи, когда понадоблюсь.",
    "Бывай 👋",
    "Удачи с продажами!",
)

HOW_ARE_YOU = (
    "В порядке — разбираю карточки. Как у тебя дела с продажами?",
    "Нормально, работаю. Что у тебя по товарам?",
)

WHO_ARE_YOU = (
    f"Я {AI_NAME} — твой личный аналитик по маркетплейсам.\n"
    "Разбираю карточки, ищу слабые места и говорю, что чинить первым.",
)

#: Чем можем заняться — добавляется к приветствию, когда контекста нет.
MENU_HINT = (
    "Чем займёмся?\n"
    "\n"
    "• разобрать карточку\n"
    "• обсудить цену или рекламу\n"
    "• спросить что угодно про маркетплейсы"
)

# --------------------------------------------------------------------------- #
# Распознавание оттенка реплики
# --------------------------------------------------------------------------- #

_MORNING = ("доброе утро", "с добрым утром", "утро доброе")
_EVENING = ("добрый вечер", "вечер добрый", "доброй ночи", "спокойной ночи")
_GREET = ("привет", "здравств", "хай", "хеллоу", "приветствую", "ку", "добрый день")
_THANKS = ("спасибо", "спс", "благодар", "пасиб", "мерси")
_BYE = ("пока", "до свидания", "увидимся", "бывай")
_HOW = ("как дела", "как ты", "как жизнь", "что нового", "как настроение")
_WHO = ("ты кто", "кто ты", "что умеешь", "что ты умеешь", "твои возможности")


def _pick(options: tuple[str, ...], seed: str) -> str:
    """Псевдослучайный выбор: разные ответы, но без повторов подряд."""
    return random.choice(options)


def reply(text: str, product=None) -> str:
    """
    Ответ на бытовую реплику.

    product — последний разобранный товар (может быть None).
    Если он есть, Seller AI напомнит о нём вместо общего меню.
    """

    text = _normalize(text)

    # --- Прощание: контекст не нужен ---
    if any(word in text for word in _BYE):
        return _pick(BYE, text)

    # --- Кто ты ---
    if any(word in text for word in _WHO):
        return WHO_ARE_YOU[0]

    # --- Как дела ---
    if any(word in text for word in _HOW):
        return _pick(HOW_ARE_YOU, text)

    # --- Благодарность ---
    if any(word in text for word in _THANKS):
        return _pick(THANKS, text)

    # --- Приветствие ---
    if any(word in text for word in _MORNING):
        opening = _pick(MORNING, text)
    elif any(word in text for word in _EVENING):
        opening = _pick(EVENING, text)
    elif any(word in text for word in _GREET):
        opening = _pick(GREETINGS, text)
    else:
        # Короткое «ок», «понял», «ага».
        return _pick(ACK, text)

    return f"{opening}\n\n{_tail(product)}"


def _tail(product) -> str:
    """Вторая часть приветствия: с опорой на последний товар или меню."""

    if product is None:
        return MENU_HINT

    title = (product.title or "последний товар")[:45]

    return (
        f"В прошлый раз мы разбирали «{title}».\n"
        "Продолжим по нему или возьмём новый товар?"
    )
