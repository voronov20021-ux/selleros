def build_system(intent: Intent, extra: str = "") -> str:
    """Финальный системный промпт: ядро + плейбук под тип вопроса."""

    # Имя подставляется из ЕДИНСТВЕННОГО места — backend/config.py.
    core = SYSTEM_PROMPT.format(ai_name=AI_NAME)

    parts = [core]

    playbook = PLAYBOOKS.get(intent)
    if playbook:
        parts.append(playbook)

    if extra:
        parts.append(extra)

    return "\n\n".join(parts)
