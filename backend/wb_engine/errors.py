"""
errors.py — три чётких исхода запроса к источнику данных.

Главный баг старого парсера был именно здесь: WBWorker после
исчерпания повторов выбрасывал ОБЫЧНЫЙ Exception, WBGateway его
не ловил — и вместо перехода к следующему источнику всё падало
наружу. WBEngine эту ошибку не повторяет: он ловит ровно эти три
класса и знает, что делать с каждым.
"""


class WBSourceError(Exception):
    """Базовый класс. WBEngine ловит его и решает, что делать дальше."""


class SourceBlocked(WBSourceError):
    """
    Источник временно недоступен — 429 или похожая блокировка.

    WBEngine запоминает это ПО ЭТОМУ источнику (не по всем сразу)
    и на время перестаёт его дёргать, а к остальным источникам
    идёт как ни в чём не бывало.
    """


class SourceNotFound(WBSourceError):
    """
    Источник ответил чётко: такого товара нет.

    В отличие от SourceBlocked, это окончательный ответ —
    WBEngine прекращает перебор и возвращает None, не мучая
    остальные источники понапрасну.
    """


class SourceUnavailable(WBSourceError):
    """
    Сеть, таймаут, сервер лёг — обычная временная неполадка.

    Не блокировка по существу, но и не результат.
    WBEngine просто переходит к следующему источнику.
    """
